export function findBarangaySchedule(barangayName) {
  if (!barangayName) return null;

  const normalized = barangayName.toLowerCase().trim();

  if (
    normalized.includes("poblacion") ||
    normalized.includes("district i") ||
    normalized.includes("district ii") ||
    normalized.includes("district iii") ||
    normalized.includes("district iv") ||
    normalized.includes("university of antique")
  ) {
    return {
      group: "Poblacion and UA Special Collection",
      description: "Special collection schedule for Poblacion and University of Antique area",
      time: "7:00 AM - 11:00 AM",
      wasteCategory: "Residual and Compostable Wastes",
      barangays: [
        "Barangay Poblacion",
        "District I",
        "District II",
        "District III",
        "District IV",
        "University of Antique",
      ],
      assignedDropOffSchedule:
        "District I: Friday / Tuesday along Mayor Santiago Lotilla St. only; District II: Wednesday; District III: Monday; District IV: Saturday; UA: Friday",
    };
  }

  const schedule = collectionSchedule.find((group) =>
    group.barangays.some(
      (barangay) => barangay.toLowerCase().trim() === normalized
    )
  );

  if (schedule) return schedule;

  const inaccessible = inaccessibleBarangays.find(
    (item) => item.barangay.toLowerCase().trim() === normalized
  );

  if (inaccessible) {
    return {
      group: "Inaccessible Barangay",
      description: "Bring residual waste to reachable collection area",
      time: "Based on assigned drop-off schedule",
      wasteCategory: "Residual Waste Only",
      barangays: [inaccessible.barangay],
      assignedDropOffSchedule: inaccessible.assignedDropOffSchedule,
    };
  }

  return null;
}